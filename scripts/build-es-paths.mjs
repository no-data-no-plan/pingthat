/**
 * Post-build: emit functions/_es-paths.gen.js so the CF Pages Functions
 * middleware can validate that an ES counterpart exists before issuing a
 * 302 to /es/{path}. Without this gate, the geo-redirect would happily
 * send Spanish-locale visitors to /es/some-tool/ that 404s.
 *
 * Source of truth is dist/es/**\/index.html — those are the pages Astro
 * actually built. Stripping the leading /es so the EN equivalent path
 * (which is what the middleware sees in url.pathname) matches the keys
 * directly.
 *
 * Output: functions/_es-paths.gen.js exporting an ES_PATHS Set.
 */

import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, posix } from 'node:path';

const DIST_ES = './dist/es';
const OUT = './functions/_es-paths.gen.js';

if (!existsSync(DIST_ES)) {
  console.warn('[build-es-paths] dist/es/ missing — emitting empty set');
  writeFileSync(OUT, 'export const ES_PATHS = new Set();\n');
  process.exit(0);
}

function* walk(dir, base = '') {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    const rel = base ? posix.join(base, entry) : entry;
    if (st.isDirectory()) {
      yield* walk(full, rel);
    } else if (entry === 'index.html') {
      // dist/es/dns-lookup/index.html → /dns-lookup/
      // dist/es/index.html             → /
      yield base ? `/${base}/` : '/';
    }
  }
}

const paths = new Set();
for (const p of walk(DIST_ES)) paths.add(p);

const sorted = [...paths].sort();
const body = `// Auto-generated by scripts/build-es-paths.mjs — do not edit.
// Lists every path under /es/ that exists in dist/, so the middleware
// can avoid redirecting to a 404 when no Spanish counterpart was built.
export const ES_PATHS = new Set([
${sorted.map(p => `  ${JSON.stringify(p)},`).join('\n')}
]);
`;

writeFileSync(OUT, body);
console.log(`[build-es-paths] wrote ${sorted.length} paths to ${OUT}`);
